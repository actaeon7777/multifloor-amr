#!/usr/bin/env python3
"""Create matched occupancy maps and PhysX collision boxes from one grid."""
import json
from pathlib import Path
import numpy as np
from PIL import Image
import yaml

ROOT=Path(__file__).resolve().parents[1]
STACK=ROOT/'src/amr_system/amr_stack'


def boxes_from_grid(occupied, resolution, origin):
    """Merge identical horizontal occupied runs vertically; preserve every occupied cell."""
    active={}; boxes=[]; h,w=occupied.shape
    def finish(run, start, end):
        x0,x1=run
        boxes.append({'name':f'wall_{len(boxes)}',
                      'center':[origin[0]+(x0+x1)*resolution/2,
                                origin[1]+(h-(start+end)/2)*resolution,.5],
                      'size':[(x1-x0)*resolution,(end-start)*resolution,1.]})
    for row in range(h+1):
        runs=[]
        if row<h:
            padded=np.pad(occupied[row].astype(int),(1,1))
            edges=np.flatnonzero(np.diff(padded))
            runs=list(zip(edges[::2].tolist(),edges[1::2].tolist()))
        present=set(runs)
        for run in list(active):
            if run not in present:finish(run,active.pop(run),row)
        for run in runs:active.setdefault(run,row)
    return boxes


def save(name, grid, resolution=.05, origin=(-5.,-5.,0.), dynamic=None):
    out=STACK/f'maps/sim_{name}';out.mkdir(parents=True,exist_ok=True)
    Image.fromarray(grid).save(out/f'{name}.pgm')
    (out/f'{name}.yaml').write_text(yaml.safe_dump({'image':f'{name}.pgm','mode':'trinary',
        'resolution':resolution,'origin':list(origin),'negate':0,'occupied_thresh':.65,'free_thresh':.196},sort_keys=False))
    world={'name':name,'resolution':resolution,'origin':list(origin),'size':[grid.shape[1],grid.shape[0]],
           'map':str((out/f'{name}.yaml').relative_to(ROOT)),
           'boxes':boxes_from_grid(grid<80,resolution,origin),'dynamic_obstacle':dynamic}
    (ROOT/f'sim/config/{name}.json').write_text(json.dumps(world,indent=2)+'\n')


def main():
    # Test corridors are defined by free rectangles; walls exactly match rasterized maps.
    x,y=np.meshgrid(-5+(np.arange(200)+.5)*.05,5-(np.arange(200)+.5)*.05)
    cases={
        'corner_left':[(-1.,-.7,3.6,.7),(2.2,-.7,3.6,3.8)],
        'corner_right':[(-1.,-.7,3.6,.7),(2.2,-3.8,3.6,.7)],
        's_curve':[(-1.,-.75,2.25,.75),(.75,-.75,2.25,3.25),(.75,1.75,4.3,3.25)],
        'narrow':[(-1.,-.6,4.3,.6)],
    }
    for name,rects in cases.items():
        free=np.zeros_like(x,dtype=bool)
        for x0,y0,x1,y1 in rects:free|=(x>=x0)&(x<=x1)&(y>=y0)&(y<=y1)
        save(name,np.where(free,254,0).astype('uint8'))
    arena=json.loads((ROOT/'sim/config/arena.json').read_text())
    grid=np.full((200,200),254,dtype='uint8')
    for box in arena['boxes']:
        cx,cy,_=box['center'];sx,sy,_=box['size']
        grid[(abs(x-cx)<=sx/2+1e-8)&(abs(y-cy)<=sy/2+1e-8)]=0
    save('arena',grid)
    save('obstacle',grid,dynamic={'name':'introduced_obstacle','center':[1.3,0.,.5],
                                 'size':[.4,.6,1.],'appear_at_s':10.})
    # Detailed floor4 USD and its matching ROS map are generated by build_scene.sh.
    # Do not overwrite that world with the legacy PGM box extrusion.
    print('Generated synthetic test worlds; detailed floor4 is built by build_scene.sh')

if __name__=='__main__':main()
