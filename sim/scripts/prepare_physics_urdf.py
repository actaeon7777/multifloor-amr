"""Produce a physics variant while proving v28 geometry and topology are retained."""
import copy
import hashlib
import json
from physics_parameters import load_config
import math
from pathlib import Path
import subprocess
import xml.etree.ElementTree as ET
from physics_parameters import joint_resistance, validate_config

ROOT = Path(__file__).resolve().parents[2]
PACKAGE = ROOT / "src/amr_description"
SOURCE = PACKAGE / "urdf/capstone_amr.urdf"
TARGET = PACKAGE / "urdf/capstone_amr_physics.urdf"


def digest(path):
    with path.open("rb") as stream:
        return hashlib.file_digest(stream, "sha256").hexdigest()


def canonical(element):
    return (element.tag, sorted(element.attrib.items()), [canonical(child) for child in element])


def geometry_and_topology(root):
    stripped = copy.deepcopy(root)
    for joint in stripped.findall("joint"):
        for tag in ("dynamics", "limit"):
            for child in joint.findall(tag):
                joint.remove(child)
    return canonical(stripped)


def compare_expansion(left, right):
    assert left.tag == right.tag and left.attrib.keys() == right.attrib.keys()
    for key, value in left.attrib.items():
        other = right.attrib[key]
        try:
            a, b = list(map(float, value.split())), list(map(float, other.split()))
        except ValueError:
            assert value == other, (left.tag, key, value, other)
        else:
            assert len(a) == len(b) and all(math.isclose(x, y, rel_tol=1e-10, abs_tol=1e-12) for x, y in zip(a, b)), (left.tag, key)
    assert len(left) == len(right), left.tag
    for a, b in zip(left, right):
        compare_expansion(a, b)


def main():
    config = load_config(ROOT)
    validate_config(config)
    drive, caster = config["drive"], config["caster"]
    original = ET.parse(SOURCE).getroot()
    output = copy.deepcopy(original)
    changes = []
    for joint in output.findall("joint"):
        name = joint.attrib["name"]
        if name in ("left_drive_wheel_joint", "right_drive_wheel_joint"):
            limit = ET.SubElement(joint, "limit") if joint.find("limit") is None else joint.find("limit")
            limit.set("effort", str(drive["effort_limit_nm"]))
            limit.set("velocity", str(drive["velocity_limit_rad_s"]))
        elif not name.endswith(("_caster_swivel_joint", "_caster_wheel_joint")):
            continue
        resistance = joint_resistance(config, name)
        values = {"damping": resistance["viscous_damping_nm_s_per_rad"], "friction": resistance["dynamic_friction_nm"]}
        dynamics = joint.find("dynamics")
        if dynamics is None:
            dynamics = ET.SubElement(joint, "dynamics")
        dynamics.attrib.update({key: str(value) for key, value in values.items()})
        changes.append(name)
    assert len(changes) == 10
    assert geometry_and_topology(original) == geometry_and_topology(output)
    ET.indent(output, space="  ")
    ET.ElementTree(output).write(TARGET, encoding="utf-8", xml_declaration=True)

    xacro_source = PACKAGE / "urdf/capstone_amr.urdf.xacro"
    xacro = xacro_source.read_text()
    replacements = {
        '<dynamics damping="0.1" friction="0.05"/>':
            f'<dynamics damping="{drive["joint_resistance"]["viscous_damping_nm_s_per_rad"]}" friction="{drive["joint_resistance"]["dynamic_friction_nm"]}"/>\n'
            f'      <limit effort="{drive["effort_limit_nm"]}" velocity="{drive["velocity_limit_rad_s"]}"/>',
        '<dynamics damping="0.08" friction="0.02"/>':
            f'<dynamics damping="{caster["swivel_resistance"]["viscous_damping_nm_s_per_rad"]}" friction="{caster["swivel_resistance"]["dynamic_friction_nm"]}"/>',
        '<dynamics damping="0.02" friction="0.01"/>':
            f'<dynamics damping="{caster["axle_resistance"]["viscous_damping_nm_s_per_rad"]}" friction="{caster["axle_resistance"]["dynamic_friction_nm"]}"/>',
    }
    for old, new in replacements.items():
        assert xacro.count(old) == 1, f"Source Xacro changed; review transformation: {old}"
        xacro = xacro.replace(old, new)
    xacro_target = PACKAGE / "urdf/capstone_amr_physics.urdf.xacro"
    xacro = xacro.replace("<robot xmlns:xacro=", "<!-- Generated by prepare_physics_urdf.py; edit source Xacro and physics.json. -->\n<robot xmlns:xacro=", 1)
    xacro_target.write_text(xacro)
    tool_python = ROOT / "runtime/urdf-tools/bin/python"
    assert tool_python.is_file(), "Install the workspace URDF tools environment first"
    for xacro_path, urdf_root in ((xacro_source, original), (xacro_target, output)):
        expanded = subprocess.check_output([str(tool_python), "-c", "import sys, xacro; print(xacro.process_file(sys.argv[1]).toxml())", str(xacro_path)])
        compare_expansion(ET.fromstring(expanded), urdf_root)

    links = {link.attrib["name"]: link for link in output.findall("link")}
    joints = output.findall("joint")
    parents = {}
    for joint in joints:
        parent, child = joint.find("parent").attrib["link"], joint.find("child").attrib["link"]
        assert parent in links and child in links and child not in parents
        parents[child] = parent
    roots = set(links) - set(parents)
    assert roots == {"base_footprint"}
    for name in links:
        seen = set()
        while name in parents:
            assert name not in seen, "Cyclic link tree"
            seen.add(name)
            name = parents[name]
        assert name in roots
    mass = 0.0
    for link in links.values():
        inertial = link.find("inertial")
        if inertial is None:
            continue
        value = float(inertial.find("mass").attrib["value"])
        assert math.isfinite(value) and value > 0
        mass += value
        inertia = {k: float(v) for k, v in inertial.find("inertia").attrib.items()}
        assert all(math.isfinite(v) for v in inertia.values())
        assert all(inertia[k] == 0 for k in ("ixy", "ixz", "iyz")), "Revalidate non-diagonal inertia with eigenvalues"
        diagonal = [inertia[k] for k in ("ixx", "iyy", "izz")]
        assert min(diagonal) > 0 and 2 * max(diagonal) <= sum(diagonal) + 1e-12
    assert math.isclose(mass, 18.0, abs_tol=1e-9)
    assert {"lidar_mount_link", "lidar_link", "laser", "imu_link"} <= links.keys()
    meshes = {}
    for mesh in output.iter("mesh"):
        path = (SOURCE.parent / mesh.attrib["filename"]).resolve()
        assert path.is_file(), path
        meshes[str(path.relative_to(PACKAGE))] = digest(path)
    # The original hashes travel with the workspace; rebuilding must not need
    # a second copy of amr_description beside it.
    snapshot = json.loads((ROOT / "reports/source_snapshot.json").read_text())
    original_hashes = snapshot["files_sha256"]
    assert digest(SOURCE) == original_hashes["urdf/capstone_amr.urdf"], "Working baseline diverged from supplied source snapshot"
    assert digest(xacro_source) == original_hashes["urdf/capstone_amr.urdf.xacro"], "Source Xacro diverged from supplied source snapshot"
    for relative, checksum in meshes.items():
        assert checksum == original_hashes[relative], relative
    report = {
        "passed": True, "source": str(SOURCE.relative_to(ROOT)), "output": str(TARGET.relative_to(ROOT)),
        "source_sha256": digest(SOURCE), "output_sha256": digest(TARGET),
        "links": len(links), "joints": len(joints), "mass_kg": mass,
        "geometry_topology_inertia_preserved": True, "xacro_expansion_matches": True, "source_meshes_sha256": meshes,
        "modified_joint_parameters": changes,
        "checks": ["connected acyclic tree", "positive physical diagonal inertias", "mesh references resolve", "original mesh hashes match", "sensor frames preserved"],
        "runtime_verified": False,
    }
    (ROOT / "reports/urdf_validation.json").write_text(json.dumps(report, indent=2) + "\n")
    print(f"Prepared {TARGET}; verified {len(links)} links, {len(joints)} joints, {mass:.1f} kg; geometry preserved.")


if __name__ == "__main__":
    main()
